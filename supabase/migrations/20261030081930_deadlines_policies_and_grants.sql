-- Issue #108: privileges and RLS policies of the deadlines.
--
-- Two layers, as in the base schema and the things to do:
-- 1. Privileges: the app writes only the content of a deadline. Never id, author or
--    the times of the row: they are set by the database. anon has no privilege at all.
-- 2. RLS policies, `to authenticated` only. A deadline is visible to the caller when it
--    belongs to the caller's household and it is «Tutto il Nest», or the caller created
--    it. «Solo io» deadlines of the others are never readable, changeable or deletable,
--    and never counted, from the API (decision of Francesco, 30/10).
--    Every member who sees a deadline reads it, changes it and deletes it (shared
--    deadlines: anybody in the household, same rule as the shared things to do decided
--    on 29/10); only the author changes «Solo io» (deadlines_before_update trigger).
-- Membership is checked with `household_id = (select public.current_household_id())`:
-- one account belongs to at most one household, the subquery runs once per statement.
-- No policy reads another table: the member of the caller comes from the security
-- definer helper private.current_member_id().

-- ---------------------------------------------------------------------------
-- Privileges on the table
-- ---------------------------------------------------------------------------

revoke all on table public.deadlines from anon, authenticated;
grant select on table public.deadlines to authenticated;
-- No id (LEZIONI: generated by the database), no author, no row times.
grant insert (
  household_id, title, due_date, note, assignee_member_id, for_member_id, is_private, reminder_days
) on table public.deadlines to authenticated;
-- Edit sheet of page #22.
grant update (
  title, due_date, note, assignee_member_id, for_member_id, is_private, reminder_days
) on table public.deadlines to authenticated;
-- «Elimina» of the edit sheet (#22); page tests empty the deadlines of their household
-- with the user session.
grant delete on table public.deadlines to authenticated;

-- ---------------------------------------------------------------------------
-- Privileges on functions
-- ---------------------------------------------------------------------------

-- Trigger and internal functions are never called directly.
revoke execute on function private.deadlines_before_insert() from public, anon, authenticated;
revoke execute on function private.deadlines_before_update() from public, anon, authenticated;
revoke execute on function private.household_members_delete_private_deadlines() from public, anon, authenticated;

-- Called by the guard triggers, evaluated as the caller. The private schema is not
-- exposed by the Data API: the app cannot call it as RPC.
revoke execute on function private.deadlines_check_assignee(uuid, uuid) from public, anon;
grant execute on function private.deadlines_check_assignee(uuid, uuid) to authenticated;
revoke execute on function private.deadlines_normalize(public.deadlines) from public, anon;
grant execute on function private.deadlines_normalize(public.deadlines) to authenticated;

-- ---------------------------------------------------------------------------
-- Policies
-- ---------------------------------------------------------------------------

drop policy if exists deadlines_select on public.deadlines;
create policy deadlines_select on public.deadlines
  for select to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );

-- New deadlines always belong to the caller (the author is set by the before insert
-- trigger).
drop policy if exists deadlines_insert on public.deadlines;
create policy deadlines_insert on public.deadlines
  for insert to authenticated
  with check (
    household_id = (select public.current_household_id())
    and created_by_member_id = (select private.current_member_id())
  );

-- The changed deadline must still be visible to the caller.
drop policy if exists deadlines_update on public.deadlines;
create policy deadlines_update on public.deadlines
  for update to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  )
  with check (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );

drop policy if exists deadlines_delete on public.deadlines;
create policy deadlines_delete on public.deadlines
  for delete to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );
