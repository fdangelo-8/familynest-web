-- Issue #87: privileges and RLS policies of the things to do.
--
-- Two layers, as in the base schema:
-- 1. Privileges: the app writes only the content of a thing to do and done_at. Never
--    id, author, «fatto da» or the times of the row: they are set by the database.
--    anon has no privilege at all.
-- 2. RLS policies, `to authenticated` only. A thing is visible to the caller when it
--    belongs to the caller's household and it is «Tutto il Nest», or the caller created
--    it. «Solo io» things of the others are never readable, changeable or deletable,
--    and never counted, from the API.
--    Every member who sees a thing reads it, marks it done or to do again, changes it
--    and deletes it; only the author changes «Solo io» (todos_before_update trigger).
-- Membership is checked with `household_id = (select public.current_household_id())`:
-- one account belongs to at most one household, the subquery runs once per statement.
-- No policy reads another table: the member of the caller comes from the security
-- definer helper private.current_member_id().

-- ---------------------------------------------------------------------------
-- Privileges on the table
-- ---------------------------------------------------------------------------

revoke all on table public.todos from anon, authenticated;
grant select on table public.todos to authenticated;
-- No id (LEZIONI: generated by the database), no author, no done_at (a new thing is
-- always to do), no «fatto da», no row times.
grant insert (
  household_id, title, assignee_member_id, for_member_id, due_date, is_private
) on table public.todos to authenticated;
-- done_at for page #23; the other columns for the edit sheet of page #22.
grant update (
  title, assignee_member_id, for_member_id, due_date, is_private, done_at
) on table public.todos to authenticated;
-- Page tests empty the things of their household with the user session; the «Elimina»
-- of the edit sheet belongs to page #22 (issue #23, question 9).
grant delete on table public.todos to authenticated;

-- ---------------------------------------------------------------------------
-- Privileges on functions
-- ---------------------------------------------------------------------------

-- Trigger and internal functions are never called directly.
revoke execute on function private.todos_before_insert() from public, anon, authenticated;
revoke execute on function private.todos_before_update() from public, anon, authenticated;
revoke execute on function private.household_members_delete_private_todos() from public, anon, authenticated;
revoke execute on function private.purge_done_todos() from public, anon, authenticated;

-- Called by the guard triggers, evaluated as the caller. The private schema is not
-- exposed by the Data API: the app cannot call it as RPC.
revoke execute on function private.todos_check_assignee(uuid, uuid) from public, anon;
grant execute on function private.todos_check_assignee(uuid, uuid) to authenticated;

-- ---------------------------------------------------------------------------
-- Policies
-- ---------------------------------------------------------------------------

drop policy if exists todos_select on public.todos;
create policy todos_select on public.todos
  for select to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );

-- New things always belong to the caller (the author is set by the before insert
-- trigger) and are always to do.
drop policy if exists todos_insert on public.todos;
create policy todos_insert on public.todos
  for insert to authenticated
  with check (
    household_id = (select public.current_household_id())
    and created_by_member_id = (select private.current_member_id())
    and done_at is null
  );

-- The changed thing must still be visible to the caller.
drop policy if exists todos_update on public.todos;
create policy todos_update on public.todos
  for update to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  )
  with check (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );

drop policy if exists todos_delete on public.todos;
create policy todos_delete on public.todos
  for delete to authenticated
  using (
    household_id = (select public.current_household_id())
    and (not is_private or created_by_member_id = (select private.current_member_id()))
  );
