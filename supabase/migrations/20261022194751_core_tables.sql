-- Base tables (issue #9): households, household_members, invitations, profiles.
-- RLS is enabled here, in the same migration that creates each table.
-- Policies and grants are in the rls_policies_and_grants migration: until then
-- RLS denies every row to the API roles.
--
-- Text normalisation (trimming) and rules that depend on "today" or on other rows
-- are enforced by triggers in the functions_and_triggers migration.

-- ---------------------------------------------------------------------------
-- households: the "Nest".
-- ---------------------------------------------------------------------------
create table public.households (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  household_type public.household_type not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint households_name_trimmed check (name = btrim(name, E' \t\r\n')),
  constraint households_name_length check (char_length(name) between 1 and 60)
);

alter table public.households enable row level security;

-- ---------------------------------------------------------------------------
-- household_members: adults (with or without account), children and pets.
-- Children and pets never have an account (privacy skill).
-- No health data of any kind (decision D1).
-- ---------------------------------------------------------------------------
create table public.household_members (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references public.households (id) on delete cascade,
  kind public.member_kind not null,
  name text not null,
  color public.member_color not null,
  birth_date date,
  user_id uuid references auth.users (id) on delete cascade,
  is_admin boolean not null default false,
  joined_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  -- Colour is unique inside a household (mockup 03, 08, 27). Also serves as the
  -- index on the household_id foreign key (leading column).
  constraint household_members_household_color_key unique (household_id, color),
  -- One household per account (v1, decision 1). Nulls are distinct: many members without account.
  constraint household_members_user_id_key unique (user_id),
  constraint household_members_name_trimmed check (name = btrim(name, E' \t\r\n')),
  constraint household_members_name_length check (char_length(name) between 1 and 40),
  constraint household_members_adult_no_birth_date check (kind <> 'adult' or birth_date is null),
  constraint household_members_account_only_adult check (user_id is null or kind = 'adult'),
  constraint household_members_admin_needs_account check (not is_admin or (kind = 'adult' and user_id is not null)),
  constraint household_members_joined_iff_account check ((user_id is null) = (joined_at is null))
);

-- Members are listed in insertion order (mockup 03, 18, 28).
create index household_members_household_created_idx
  on public.household_members (household_id, created_at);

alter table public.household_members enable row level security;

-- ---------------------------------------------------------------------------
-- invitations: invitation of an adult already added to the household.
-- ---------------------------------------------------------------------------
create table public.invitations (
  id uuid primary key default gen_random_uuid(),
  household_id uuid not null references public.households (id) on delete cascade,
  member_id uuid not null references public.household_members (id) on delete cascade,
  invited_by_member_id uuid references public.household_members (id) on delete set null,
  -- 256 random bits, hex encoded: never derived from ids.
  token text not null default encode(extensions.gen_random_bytes(32), 'hex'),
  -- 4 digits, generated by trigger, unique among valid (pending, not expired) invitations.
  short_code text not null,
  message text,
  status public.invitation_status not null default 'pending',
  expires_at timestamptz not null default (now() + interval '7 days'),
  accepted_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint invitations_token_key unique (token),
  constraint invitations_token_length check (char_length(token) >= 32),
  constraint invitations_short_code_format check (short_code ~ '^[0-9]{4}$'),
  constraint invitations_message_length check (message is null or char_length(message) between 1 and 280),
  constraint invitations_accepted_at_iff_accepted check ((status = 'accepted') = (accepted_at is not null))
);

create index invitations_household_id_idx on public.invitations (household_id);
create index invitations_member_id_idx on public.invitations (member_id);
create index invitations_invited_by_member_id_idx on public.invitations (invited_by_member_id);
-- At most one pending invitation per member.
create unique index invitations_one_pending_per_member_idx
  on public.invitations (member_id)
  where status = 'pending';
-- Lookup of pending invitations by short code.
create index invitations_pending_short_code_idx
  on public.invitations (short_code)
  where status = 'pending';

alter table public.invitations enable row level security;

-- ---------------------------------------------------------------------------
-- profiles: one row per account, created by trigger on auth.users.
-- The email is never copied here: it stays in auth.users.
-- ---------------------------------------------------------------------------
create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_display_name_trimmed check (display_name is null or display_name = btrim(display_name, E' \t\r\n')),
  constraint profiles_display_name_length check (display_name is null or char_length(display_name) between 1 and 100)
);

alter table public.profiles enable row level security;
