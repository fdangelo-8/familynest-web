-- Issue #219: privileges and RLS policies of the school, sizes and teachers of a child.
--
-- Two layers, as in the base schema:
-- 1. Privileges: the app reads, and writes only the content (never id, household, kind,
--    sizes_updated_at or the row times: the database sets them). The page saves with
--    save_child_profile(); direct writes go through the same triggers (normalisation, sizes
--    time, limit of five teachers). anon has no privilege at all.
-- 2. RLS policies, `to authenticated` only. School, sizes and teachers of a child are seen
--    and changed by every adult with an account of the child's household, administrator or
--    not (issue #31); every other household reads 0 rows and cannot insert, change or delete
--    them. No exception for the public wish list (D2) or the invitation preview: no other
--    function reads these tables.
-- Membership is checked with `household_id = (select public.current_household_id())`: one
-- account belongs to at most one household, the subquery runs once per statement. No policy
-- reads another table; that the member is a child of the same household is guaranteed by the
-- composite foreign key.

-- ---------------------------------------------------------------------------
-- Privileges on the tables
-- ---------------------------------------------------------------------------

revoke all on table public.child_profiles from anon, authenticated;
grant select on table public.child_profiles to authenticated;
-- No id (LEZIONI: generated by the database), no household, no kind, no times.
grant insert (
  member_id, school_name, school_class, school_starts_at, school_ends_at, school_days, school_note,
  shoe_size, clothing_size, pajama_size
) on table public.child_profiles to authenticated;
grant update (
  school_name, school_class, school_starts_at, school_ends_at, school_days, school_note,
  shoe_size, clothing_size, pajama_size
) on table public.child_profiles to authenticated;
grant delete on table public.child_profiles to authenticated;

revoke all on table public.child_teachers from anon, authenticated;
grant select on table public.child_teachers to authenticated;
-- No id (LEZIONI: generated by the database), no household, no kind, no times.
grant insert (member_id, sort_order, name, subject, phone) on table public.child_teachers to authenticated;
grant update (sort_order, name, subject, phone) on table public.child_teachers to authenticated;
grant delete on table public.child_teachers to authenticated;

-- ---------------------------------------------------------------------------
-- Privileges on functions
-- ---------------------------------------------------------------------------

-- Trigger functions, never called directly.
revoke execute on function private.child_profiles_before_write() from public, anon, authenticated;
revoke execute on function private.child_teachers_before_write() from public, anon, authenticated;

-- Operation for signed-in users only.
revoke execute on function public.save_child_profile(
  uuid, text, public.member_color, jsonb, date, text, text, time, time, smallint[], text, text, text, text
) from public, anon;
grant execute on function public.save_child_profile(
  uuid, text, public.member_color, jsonb, date, text, text, time, time, smallint[], text, text, text, text
) to authenticated;

-- ---------------------------------------------------------------------------
-- Policies of child_profiles
-- ---------------------------------------------------------------------------

drop policy if exists child_profiles_select on public.child_profiles;
create policy child_profiles_select on public.child_profiles
  for select to authenticated
  using (household_id = (select public.current_household_id()));

-- The household is set by the before insert trigger.
drop policy if exists child_profiles_insert on public.child_profiles;
create policy child_profiles_insert on public.child_profiles
  for insert to authenticated
  with check (household_id = (select public.current_household_id()));

drop policy if exists child_profiles_update on public.child_profiles;
create policy child_profiles_update on public.child_profiles
  for update to authenticated
  using (household_id = (select public.current_household_id()))
  with check (household_id = (select public.current_household_id()));

drop policy if exists child_profiles_delete on public.child_profiles;
create policy child_profiles_delete on public.child_profiles
  for delete to authenticated
  using (household_id = (select public.current_household_id()));

